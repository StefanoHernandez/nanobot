// Inlines katex.min.css with woff2 fonts as base64 data URIs (the WebView has no file/network access).
import { readFileSync, writeFileSync } from "node:fs";
const dist = new URL("../node_modules/katex/dist/", import.meta.url);
const css = readFileSync(new URL("katex.min.css", dist), "utf8")
  // drop woff/ttf fallbacks, keep woff2 only
  .replace(/,url\(fonts\/[^)]+\.woff\) format\("woff"\),url\(fonts\/[^)]+\.ttf\) format\("truetype"\)/g, "")
  .replace(/url\(fonts\/([^)]+\.woff2)\)/g, (_, f) =>
    `url(data:font/woff2;base64,${readFileSync(new URL(`fonts/${f}`, dist)).toString("base64")})`);
const out = new URL("../src/ui/markdown/katexCss.generated.ts", import.meta.url);
writeFileSync(out, `// Generated by scripts/gen-katex-css.mjs (npm run gen:katex). Do not edit.\nexport const KATEX_CSS = ${JSON.stringify(css)};\n`);
console.log("bytes:", css.length);
